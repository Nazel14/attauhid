/**
 * ✅ FIXED: Cari halaman dan portion untuk ayat tertentu
 */
function getAccuratePageAndPortion(surahNum, ayatNum) {
    if (!completeQuranMapping[surahNum]) {
        console.warn(`⚠️ Data surat ${surahNum} tidak ditemukan`);
        return null;
    }
    
    const surahData = completeQuranMapping[surahNum];
    const startPage = surahData.startPage;
    const pageBreaks = surahData.ayatPerPage;
    
    // Cari halaman dimana ayat berada
    let currentPage = startPage;
    let previousBreak = 0;
    let nextBreak = pageBreaks[0];
    
    for (let i = 0; i < pageBreaks.length; i++) {
        if (ayatNum <= pageBreaks[i]) {
            currentPage = startPage + i;
            nextBreak = pageBreaks[i];
            previousBreak = (i === 0) ? 0 : pageBreaks[i - 1];
            break;
        }
    }
    
    // Hitung portion (persentase dalam halaman)
    const ayatInPage = nextBreak - previousBreak;
    const ayatPosition = ayatNum - previousBreak - 1;
    const portion = (ayatPosition / ayatInPage) * 100;
    
    return {
        page: currentPage,
        portion: Math.max(0, Math.min(100, Math.round(portion * 100) / 100)),
        ayatRange: `${previousBreak + 1}-${nextBreak}`,
        ayatInPage,
        firstAyatInPage: previousBreak + 1,
        lastAyatInPage: nextBreak
    };
}

/**
 * ✅ FIXED: Hitung total ayat dalam 1 halaman dengan null checks
 */
function getTotalAyatInPage(pageNum) {
    let totalAyat = 0;
    
    for (let surahNum = 1; surahNum <= 114; surahNum++) {
        const data = completeQuranMapping[surahNum];
        if (!data) continue;
        
        // Cek apakah halaman ini ada di surat ini
        if (pageNum >= data.startPage && pageNum <= data.endPage) {
            const pageIndex = pageNum - data.startPage;
            
            // ✅ FIX: Pastikan ayatPerPage ada dan valid
            if (!data.ayatPerPage || !Array.isArray(data.ayatPerPage)) {
                console.warn(`⚠️ ayatPerPage tidak valid untuk surat ${surahNum}`);
                continue;
            }
            
            // ✅ FIX: Cek index tidak out of bounds
            if (pageIndex >= data.ayatPerPage.length) {
                console.warn(`⚠️ pageIndex ${pageIndex} melebihi array length untuk surat ${surahNum}`);
                continue;
            }
            
            const firstAyat = (pageIndex === 0) ? 1 : (data.ayatPerPage[pageIndex - 1] || 0) + 1;
            const lastAyat = data.ayatPerPage[pageIndex] || 0;
            
            // ✅ FIX: Validasi nilai sebelum hitung
            if (lastAyat > 0 && firstAyat > 0 && lastAyat >= firstAyat) {
                const ayatCount = lastAyat - firstAyat + 1;
                totalAyat += ayatCount;
                
                console.log(`📖 Surat ${surahNum}, Page ${pageNum}: ${firstAyat}-${lastAyat} (${ayatCount} ayat)`);
            }
        }
    }
    
    console.log(`✅ Total ayat di halaman ${pageNum}: ${totalAyat}`);
    return totalAyat;
}

/**
 * ✅ FIXED v2: Hitung total halaman dari range ayat
 * FIX: Menambah perhitungan ayat untuk surat-surat di TENGAH (middle surahs)
 *      ketika surahStart dan surahEnd berada di halaman yang sama.
 * 
 * CONTOH BUG SEBELUMNYA:
 *   Al-Ikhlas (112) ayat 1 s/d An-Nas (114) ayat 6 → semua ada di halaman 604
 *   Kode LAMA: hitung surat 112 (4 ayat) + surat 114 (6 ayat) = 10/15 = 0.67 ❌
 *   Kode BARU: hitung surat 112 (4) + surat 113 (5) + surat 114 (6) = 15/15 = 1.00 ✅
 */
function calculateTotalPages(surahStart, ayatStart, surahEnd, ayatEnd) {
    const dataStart = getAccuratePageAndPortion(surahStart, ayatStart);
    const dataEnd = getAccuratePageAndPortion(surahEnd, ayatEnd);
    
    if (!dataStart || !dataEnd) {
        console.error('❌ Data tidak lengkap');
        return 0;
    }
    
    const pageStart = dataStart.page;
    const pageEnd = dataEnd.page;
    
    console.log('🔍 Debug calculation:', {
        pageStart,
        pageEnd,
        ayatStart,
        ayatEnd,
        dataStart,
        dataEnd
    });
    
    // ✅ PERBAIKAN: Jika dalam 1 halaman yang sama
    if (pageStart === pageEnd) {
        // Hitung total ayat di halaman ini (termasuk dari surat lain)
        const totalAyatInPage = getTotalAyatInPage(pageStart);
        
        // Jika totalAyatInPage = 0, gunakan fallback
        if (totalAyatInPage === 0) {
            console.warn('⚠️ Total ayat = 0, menggunakan fallback calculation');
            return 1; // Minimal 1 halaman
        }
        
        // Jika surat yang sama
        if (surahStart === surahEnd) {
            const ayatRead = ayatEnd - ayatStart + 1;
            const proportion = ayatRead / totalAyatInPage;
            
            console.log(`📊 Same surah, same page:`, {
                totalAyatInPage,
                ayatRead,
                proportion: proportion.toFixed(2)
            });
            
            return Math.round(proportion * 100) / 100;
        }
        
        // ✅ FIX: Jika beda surat dalam 1 halaman - hitung SEMUA surat termasuk surat di tengah
        let totalAyatRead = 0;

        // Ayat dari surat PERTAMA (dari ayatStart sampai akhir surat itu di halaman ini)
        const ayatFromFirstSurah = dataStart.lastAyatInPage - ayatStart + 1;
        totalAyatRead += ayatFromFirstSurah;

        // ✅ FIX UTAMA: Hitung ayat dari surat-surat di TENGAH (surahStart+1 sampai surahEnd-1)
        // Ini adalah surat-surat yang seluruh ayatnya terbaca karena berada di antara
        // surat pertama dan surat terakhir pada halaman yang sama
        for (let middleSurah = surahStart + 1; middleSurah < surahEnd; middleSurah++) {
            const middleData = completeQuranMapping[middleSurah];
            if (middleData && middleData.startPage === pageStart) {
                const ayatInMiddleSurah = middleData.totalAyat;
                totalAyatRead += ayatInMiddleSurah;
                console.log(`📖 Middle surah ${middleSurah}: +${ayatInMiddleSurah} ayat dihitung`);
            }
        }

        // Ayat dari surat TERAKHIR (dari awal surat itu sampai ayatEnd)
        const ayatFromLastSurah = ayatEnd - dataEnd.firstAyatInPage + 1;
        totalAyatRead += ayatFromLastSurah;

        const proportion = totalAyatRead / totalAyatInPage;
        
        console.log(`📊 Multi-surah in same page (FIXED):`, {
            totalAyatInPage,
            ayatFromFirstSurah,
            middleSurahsCount: surahEnd - surahStart - 1,
            ayatFromLastSurah,
            totalAyatRead,
            proportion: proportion.toFixed(2)
        });
        
        return Math.round(proportion * 100) / 100;
    }
    
    // ✅ Jika beda halaman
    let total = 0;
    
    // Halaman pertama
    const totalAyatInFirstPage = getTotalAyatInPage(pageStart);
    if (totalAyatInFirstPage > 0) {
        const ayatReadInFirstPage = dataStart.lastAyatInPage - ayatStart + 1;
        const firstPagePortion = ayatReadInFirstPage / totalAyatInFirstPage;
        total += firstPagePortion;
    } else {
        // Fallback jika data tidak ada
        total += 0.5; // Anggap setengah halaman
    }
    
    // Halaman tengah (jika ada)
    const middlePages = Math.max(0, pageEnd - pageStart - 1);
    total += middlePages;
    
    // Halaman terakhir
    const totalAyatInLastPage = getTotalAyatInPage(pageEnd);
    if (totalAyatInLastPage > 0) {
        const ayatReadInLastPage = ayatEnd - dataEnd.firstAyatInPage + 1;
        const lastPagePortion = ayatReadInLastPage / totalAyatInLastPage;
        total += lastPagePortion;
    } else {
        // Fallback jika data tidak ada
        total += 0.5; // Anggap setengah halaman
    }
    
    console.log(`📊 Multiple pages:`, {
        pageRange: `${pageStart}-${pageEnd}`,
        firstPage: (totalAyatInFirstPage > 0 ? (dataStart.lastAyatInPage - ayatStart + 1) / totalAyatInFirstPage : 0.5).toFixed(2),
        middlePages,
        lastPage: (totalAyatInLastPage > 0 ? (ayatEnd - dataEnd.firstAyatInPage + 1) / totalAyatInLastPage : 0.5).toFixed(2),
        total: total.toFixed(2)
    });
    
    return Math.round(total * 100) / 100;
}

